// Differential workload for the F3 JIT, milestone F3 -- dimension: **a dispatched call emitted as
// a real native call**, behind the very inline-cache guard that used to gate only an expansion.
//
// Everything here is written against one hazard: a site that binds `invokevirtual` or
// `invokeinterface` to a *compiled address* is right only while the receiver is of the class that
// address was chosen for. So every native call site below is shown **two** receiver classes whose
// bodies compute different arithmetic -- the warm half fixes the guard, the drifting half makes it
// miss -- and a guard that is missing, that checks the wrong thing, or that does not deopt moves
// the answer rather than merely the speed.
//
// The reason the callees are enormous is that they must be **impossible to inline**: with
// `MAX_INLINE_BYTES` at 2048 a ~2.5 kB body busts the budget on its own, so the site has no answer
// left but a real call -- while staying under `MAX_CODE_LEN` (4096) so the callee itself compiles
// and its `NativeRecord` really fills. None of them allocates or writes a reference field, which is
// what keeps their records callable at all (see `JitCache::install`).
//
//   NkBig/NkBigB.big       site A -- a monomorphic virtual native call, then a drifting one.
//   NkBig/NkBigB.mix       site B -- a natively called callee that itself **deopts**, from an
//                                    inner dispatched site whose receiver drifts, and is then
//                                    resumed by the interpreter *to a value*: two rebuilt frames
//                                    and an answer, not an exception.
//   NkTop.viaTop           site C -- `invokeinterface` to a **default** method inherited through a
//                                    superinterface (`NkMid extends NkTop`), called natively.
//   NkL1/NkL2/NkL3.lvl*    site D -- a virtual chain three levels deep, every level a real call,
//                                    and every level shown two classes.
//   callBigSub/SubSub        site E -- the same three sites warmed with the **overriding subclass**,
//                                    so the declared owner and the guarded class's method table
//                                    name different bodies *while the guard hits*. Without this
//                                    the fixture never distinguishes the two resolutions.
//
// Compiled with the **real** JDK 25 javac, not this repo's -- the point of a differential fixture
// is to measure this VM, and a fixture built by our own compiler measures the pair.
