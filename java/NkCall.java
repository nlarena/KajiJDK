    // The call sites themselves. Each is its own method so that each compiles on its own and each
    // guard is a separate site -- and each loops, so the site is reached often enough for the
    // interpreter to have profiled a receiver class before the method is offered to the compiler.

    // Site A.
    static int callBig(NkBig o, int n) {
        int acc = 0;
        for (int i = 0; i < n; i++) {
            acc = (acc + o.big(i)) & 0xFFFFF;
        }
        return acc;
    }

    // Site B -- `holder` is the receiver of the native call, `other` the receiver of the guarded
    // site *inside* it. Two different objects, so the inner guard can miss while the outer hits,
    // which is the only way a deopt ever comes out of a frame a call created.
    static int callMix(NkBig holder, NkBig other, int n) {
        int acc = 0;
        for (int i = 0; i < n; i++) {
            acc = (acc + holder.mix(other, i)) & 0xFFFFF;
        }
        return acc;
    }

    // Site C -- `invokeinterface`, on the static type `NkMid`, to a default declared on `NkTop`.
    static int callIface(NkMid o, int n) {
        int acc = 0;
        for (int i = 0; i < n; i++) {
            acc = (acc + o.viaTop(i)) & 0xFFFFF;
        }
        return acc;
    }

    // Site D -- the outermost of the three levels.
    static int callChain(NkL1 a, NkL2 b, NkL3 c, int n) {
        int acc = 0;
        for (int i = 0; i < n; i++) {
            acc = (acc + a.lvl1(b, c, i)) & 0xFFFFF;
        }
        return acc;
    }

