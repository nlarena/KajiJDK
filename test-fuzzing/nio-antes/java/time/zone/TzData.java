package java.time.zone;

// KajiLibrary's embedded tzdb subset — the DATA behind ZoneRules.
//
// WHY A SUBSET, EXPLICITLY: the full IANA database is 604 zones and 29,425 transitions, roughly
// 88,000 numbers. That does not fit in generated Java source — the `<clinit>` would blow past the
// 64 KB method limit long before the end. The JDK ships it as a binary resource (lib/tzdb.dat,
// 102 KB) for exactly this reason. So the RULES ENGINE here is complete and general, and the data
// is a documented set of 8 zones chosen to exercise every shape the engine must handle:
//
//   UTC                             a fixed-offset zone (no transitions at all)
//   Europe/Madrid                   EU rules, transitions defined in UTC terms
//   America/New_York                US rules, defined in WALL terms
//   America/Argentina/Buenos_Aires  historical transitions, no current DST
//   Asia/Tokyo                      historical DST only (1948-51), none since
//   Australia/Sydney                SOUTHERN hemisphere — DST spans the new year
//   Asia/Kolkata                    a half-hour offset
//   Pacific/Chatham                 a 45-minute offset, the awkward one
//
// The full database becomes reachable by reading lib/tzdb.dat at runtime, which needs file I/O
// (blocked on the runtime track) — not by adding more generated source.
//
// Extracted from the JDK's own ZoneRules, not transcribed.
