    static long transitionEpoch(int zone, int i) {
        return TRANS_EPOCH[TRANS_START[zone] + i];
    }

    static int transitionBefore(int zone, int i) {
        return TRANS_BEFORE[TRANS_START[zone] + i];
    }

    static int transitionAfter(int zone, int i) {
        return TRANS_AFTER[TRANS_START[zone] + i];
    }

    static int ruleCount(int zone) {
        return RULE_COUNT[zone];
    }

    // Field `f` of rule `i` of `zone`, by the 9-int layout documented above.
    static int ruleField(int zone, int i, int f) {
        return RULES[(RULE_START[zone] + i) * 9 + f];
    }
