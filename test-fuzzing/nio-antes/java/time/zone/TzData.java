    static int zoneIndex(String zoneId) {
        String[] ids = TzData.zoneIds();
        int found = -1;
        int i = 0;
        while (i < ids.length) {
            if (ids[i].equals(zoneId)) {
                found = i;
                i = ids.length;
            } else {
                i = i + 1;
            }
        }
        return found;
    }

