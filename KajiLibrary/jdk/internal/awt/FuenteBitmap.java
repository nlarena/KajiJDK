    private static int indice(char c) {
        if (c < PRIMERO || c > ULTIMO) {
            return '?' - PRIMERO;
        }
        return c - PRIMERO;
    }

    /** Cuantos pixeles avanza el cursor despues de {@code c}. */
    public static int avance(char c) {
        return AVANCE[indice(c)];
    }

    /** La mascara de la fila {@code y} del glifo de {@code c}; ver {@link #FILAS}. */
    public static int fila(char c, int y) {
        return FILAS[indice(c) * ALTO + y];
    }
