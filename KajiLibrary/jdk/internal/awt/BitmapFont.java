    private static int index(char c) {
        if (c < FIRST || c > LAST) {
            return '?' - FIRST;
        }
        return c - FIRST;
    }

    /** How many pixels the cursor advances after {@code c}. */
    public static int advance(char c) {
        return ADVANCE[index(c)];
    }

    /** The mask of row {@code y} of the glyph of {@code c}; see {@link #ROWS}. */
    public static int row(char c, int y) {
        return ROWS[index(c) * HEIGHT + y];
    }
