/**
 * The only font of this VM: Dialog 12 of the real JDK, as a bitmap.
 *
 * <h2>Where it comes from</h2>
 *
 * <p>It is not drawn by hand. Each glyph is <strong>what the JDK 25 paints</strong> for that
 * character with {@code Dialog PLAIN 12}, antialiasing off and integer metrics, read pixel by pixel
 * from an image; and the ascent, the descent and each advance are the ones its {@code FontMetrics}
 * reports. The extractor is in the log of the session that generated it. The table is then the
 * source of truth of the project applied to the typography: our text resembles that of the JDK by
 * construction, not by a good eye.
 *
 * <h2>Why a single face</h2>
 *
 * <p>Reading a font file of the system and turning its curves into pixels is a whole typographic
 * engine, and it is not there. What is honest is the <em>substitution</em>: the JDK also draws with
 * another face when it does not have the one asked for. Here every {@code Font} is drawn with this
 * one, at this size, and the metrics that are reported are those of this one -- that way what a
 * layout calculates coincides with what is painted, which is the only thing that can be promised.
 *
 * <p>It lives in a <strong>non-exported</strong> package, like {@code sun.font} in the JDK: it is
 * public so that {@code java.awt} and {@code java.awt.image} share it, and it is not API.
 *
 * <p>The characters outside ASCII are drawn and measured as {@code ?}: it is the visible answer of
 * "this font does not have that glyph", which is preferable to a hole that looks like a space.
 */
